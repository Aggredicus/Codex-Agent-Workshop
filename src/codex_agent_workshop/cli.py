def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    root = ROOT

    if args.command == "doctor":
        return _doctor(root)

    if args.command == "teams":
        for slug in discover_teams(root):
            print(slug)
        return 0

    if args.command == "team":
        team = resolve_team(root, args.slug)
        print(json.dumps({
            "id": team.id,
            "name": team.name,
            "description": team.description,
            "roles": [role.id for role in team.roles],
        }, indent=2))
        return 0

    if args.command == "validate":
        return _validate(root, args.team)

    if args.command in {"plan", "prompt"}:
        team = resolve_team(root, args.team)
        plan = build_plan(team, args.goal, mode=args.mode)
        if args.command == "prompt":
            print(render_prompt(plan))
        elif args.json:
            print(json.dumps(plan.to_dict(), indent=2))
        else:
            print(render_plan(plan))
        return 0

    if args.command == "init-team":
        target = root / "teams" / args.slug / "team.toml"
        if target.exists() and not args.force:
            print(f"ERROR: {target} already exists; pass --force to replace it", file=sys.stderr)
            return 1
        if not args.slug or any(ch not in "abcdefghijklmnopqrstuvwxyz0123456789-" for ch in args.slug):
            print("ERROR: slug must use lowercase letters, numbers, and hyphens", file=sys.stderr)
            return 1
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_starter(args.slug, args.name), encoding="utf-8")
        print(target)
        return 0

    return 2
