from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import sys

from . import __version__
from .config import discover_teams, load_team, resolve_team
from .planner import build_plan, render_plan, render_prompt

ROOT = Path.cwd()


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="caw", description="Codex Agent Workshop")
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("doctor", help="Check local workshop readiness")

    teams = sub.add_parser("teams", help="List available teams")
    teams.add_argument("action", choices=["list"])

    team = sub.add_parser("team", help="Inspect one team")
    team.add_argument("action", choices=["show"])
    team.add_argument("slug")

    validate = sub.add_parser("validate", help="Validate team definitions")
    validate.add_argument("--team")

    for name in ("plan", "prompt"):
        cmd = sub.add_parser(name)
        cmd.add_argument("--team", default="solo-llc")
        cmd.add_argument("--goal", required=True)
        cmd.add_argument("--mode", choices=["auto", "single", "multi", "symphony"], default="auto")
        if name == "plan":
            cmd.add_argument("--json", action="store_true")

    init = sub.add_parser("init-team", help="Create a starter team definition")
    init.add_argument("slug")
    init.add_argument("--name", required=True)
    init.add_argument("--force", action="store_true")
    return parser


def _doctor(root: Path) -> int:
    checks = {
        "python": sys.version.split()[0],
        "git": shutil.which("git"),
        "codex": shutil.which("codex"),
        "AGENTS.md": (root / "AGENTS.md").exists(),
        "WORKFLOW.md": (root / "WORKFLOW.md").exists(),
        "SPEC.md": (root / "SPEC.md").exists(),
        "teams": len(discover_teams(root)),
    }
    print(json.dumps(checks, indent=2))
    hard_fail = not checks["AGENTS.md"] or not checks["WORKFLOW.md"] or not checks["SPEC.md"] or checks["teams"] == 0
    if checks["codex"] is None:
        print("NOTE: Codex CLI was not found on PATH; planning and prompt generation still work.")
    return 1 if hard_fail else 0


def _validate(root: Path, slug: str | None) -> int:
    paths = discover_teams(root)
    if slug:
        if slug not in paths:
            print(f"ERROR: unknown team {slug!r}", file=sys.stderr)
            return 1
        paths = {slug: paths[slug]}
    errors = 0
    for name, path in paths.items():
        try:
            team = load_team(path)
            print(f"OK {name}: {len(team.roles)} roles")
        except Exception as exc:
            errors += 1
            print(f"ERROR {name}: {exc}", file=sys.stderr)
    if not paths:
        print("ERROR: no teams found", file=sys.stderr)
        return 1
    return 1 if errors else 0


